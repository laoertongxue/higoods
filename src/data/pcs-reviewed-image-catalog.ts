export function reviewedStyleImage(styleCode: string, colorName?: string): string {
  const colors = PCS_STYLE_IMAGE_KEYS[styleCode]
  if (!colors) return ''
  const key = colorName === undefined ? Object.values(colors)[0] : colors[colorName]
  return PCS_IMAGE_PATHS[key] || ''
}

export function reviewedStyleGallery(styleCode: string): string[] {
  return [...new Set(Object.values(PCS_STYLE_IMAGE_KEYS[styleCode] || {}).map((key) => PCS_IMAGE_PATHS[key]))]
}

export function migrateMaterialMockImage(code: string, current: string, kind: 'material' | 'sku'): string {
  const legacy = kind === 'sku' ? legacyMaterialSkuImages : legacyMaterialMainImages
  const keys = kind === 'sku' ? PCS_MATERIAL_IMAGE_KEYS : materialMainImageKeys
  return current === legacy[code] ? PCS_IMAGE_PATHS[keys[code]] || current : current
}

export function migrateMaterialMockGallery(materialCode: string, urls: string[]): string[] {
  return [...new Set(urls.map((url) => {
    const skuCode = Object.keys(legacyMaterialSkuImages).find((code) => code.startsWith(`${materialCode}-`) && legacyMaterialSkuImages[code] === url)
    return skuCode ? migrateMaterialMockImage(skuCode, url, 'sku') : url
  }))]
}
