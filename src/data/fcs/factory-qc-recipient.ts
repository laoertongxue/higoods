import { factoryTypeConfig } from './factory-types.ts'
import { DYE_PARTNERS } from './dye-work-order-demo-details.ts'

const explicitFactoryTypes = new Map<string, boolean>(
  Object.entries(factoryTypeConfig).flatMap(([type, { label }]) => [[type, type === 'CENTRAL_DYE'], [label, type === 'CENTRAL_DYE']]),
)
// Existing dye dispatch partners use this specific print-factory classification.
explicitFactoryTypes.set('印花加工厂', false)

const centralWarehouseIds = new Set(['WH-FABRIC-001', 'WH-ACCESSORY-001', 'CENTRAL-WAREHOUSE'])
const registeredNonDyeWarehouses = new Set<string>(Object.values(DYE_PARTNERS).filter(target => target.kind === 'WAREHOUSE').map(target => target.id))
// These are business identity namespaces generated by resolveTerminalProcessOrderReceivingTarget,
// rather than factory/warehouse display names. Arbitrary unregistered warehouse IDs stay unknown.
const terminalBusinessTargetId = /^(?:CUTTING-TRANSFER-WAREHOUSE|CUTTING|EARLY-PROCESS-WAIT|EARLY-PROCESS|SUPPLEMENT-CONSUMER|SUPPLEMENT-WAREHOUSE|DESIGN-REVISION-LOCATION|DESIGN-REVISION)-[A-Za-z0-9_-]+$/

/** undefined means the downstream's dye-factory classification has not been established. */
export function classifyFactoryQcRecipient(input: { id: string; kind?: string; factoryType?: string; masterFactoryType?: string }): boolean | undefined {
  // A warehouse's owning factory has the same authority as a direct factory recipient.
  if (input.masterFactoryType !== undefined) return explicitFactoryTypes.get(input.masterFactoryType)
  if (centralWarehouseIds.has(input.id) || input.kind === 'WAREHOUSE' && (registeredNonDyeWarehouses.has(input.id) || terminalBusinessTargetId.test(input.id))) return false
  return input.factoryType === undefined ? undefined : explicitFactoryTypes.get(input.factoryType)
}
