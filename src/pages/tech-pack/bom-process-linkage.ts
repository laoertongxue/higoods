export interface SyncPreparationProcessesFromBomResult<T extends BomDrivenPrepTechniqueCandidate> {
  techniques: T[]
  generatedProcessCodes: BomDrivenPrepProcessCode[]
  removedProcessCodes: BomDrivenPrepProcessCode[]
  pendingConfirmationProcessCodes: BomDrivenPrepProcessCode[]
  generatedOccurrenceIds: string[]
  removedOccurrenceIds: string[]
  pendingConfirmationOccurrenceIds: string[]
}

type BomRouteOccurrenceSpec = {
  id: string
  bomItemId: string
  routeObjectKey: string
  processCode: string
  processName: string
  entryType: 'PROCESS_BASELINE' | 'CRAFT'
  stageCode: 'PREP' | 'PROD'
  stageName: string
  craftCode: string
  craftName: string
  isSpecialCraft: boolean
  selectedTargetObject?: '成衣' | '完整面料' | '辅料'
  inputObjectType: TechnicalProcessObjectType
  outputObjectType: TechnicalProcessObjectType
  triggerField?: BomTriggerField
  triggerSource: string
  assignmentGranularity: 'ORDER' | 'COLOR' | 'SKU'
  detailSplitDimensions: string[]
  defaultDocType: 'TASK' | 'PREPARATION_ORDER'
  taskTypeMode: 'PROCESS' | 'CRAFT'
  consumesBomItem?: boolean
}

const GARMENT_HEAT_TRANSFER_CODES = new Set(['AUX_HEAT_TRANSFER', 'HEAT_TRANSFER', 'PROC_HEAT_TRANSFER'])
const GARMENT_DIRECT_PRINT_CODES = new Set(['AUX_DIRECT_PRINT', 'DIRECT_PRINT', 'PROC_DIRECT_PRINT'])
const BINDING_STRIP_CODES = new Set(['CRAFT_131072', 'AUX_BINDING_STRIP'])
const ELASTIC_FIXED_LENGTH_CODES = new Set(['CRAFT_3000009', 'SPECIAL_ELASTIC_FIXED_LENGTH_CUTTING'])

export function normalizeBomRequirement(value: unknown): BomRequirementFlag {
  return value === '是' || value === true ? '是' : '否'
}

function toSafeId(value: string): string {
  return value.trim().replace(/[^A-Za-z0-9_-]/g, '_') || 'UNKNOWN'
}

function toBomObjectType(type: BomProcessLinkageBomRow['type']): TechnicalProcessObjectType {
  if (type === '面料') return 'FABRIC'
  if (type === '纱线') return 'YARN'
  if (type === '辅料') return 'ACCESSORY'
  if (type === '包装材料') return 'PACKAGING_MATERIAL'
  if (type === '成衣') return 'GARMENT'
  return 'BOM_MATERIAL'
}

function getRequiredPrepProcessCodesForRow(row: BomProcessLinkageBomRow): BomDrivenPrepProcessCode[] {
  if (row.type === '成衣') return []
  const codes: BomDrivenPrepProcessCode[] = []
  if (normalizeBomRequirement(row.waterSolubleRequirement) === '是') codes.push('WATER_SOLUBLE')
  if (String(row.dyeRequirement || '无') !== '无') codes.push('DYE')
  if (String(row.printRequirement || '无') !== '无') codes.push('PRINT')
  if (String(row.embroideryRequirement || '无') !== '无') codes.push('EMBROIDERY')
  return codes
}

function getBomDrivenProcessMeta(processCode: BomDrivenPrepProcessCode): {
  processName: string
  triggerField: BomTriggerField
  assignmentGranularity: 'COLOR' | 'ORDER'
  detailSplitDimensions: string[]
} {
  if (processCode === 'PRINT') {
    return {
      processName: '印花',
      triggerField: 'printRequirement',
      assignmentGranularity: 'COLOR',
      detailSplitDimensions: ['PATTERN', 'MATERIAL_SKU'],
    }
  }
  if (processCode === 'WATER_SOLUBLE') {
    return {
      processName: '水溶',
      triggerField: 'waterSolubleRequirement',
      assignmentGranularity: 'ORDER',
      detailSplitDimensions: ['MATERIAL_SKU'],
    }
  }
  if (processCode === 'EMBROIDERY') {
    return {
      processName: '绣花',
      triggerField: 'embroideryRequirement',
      assignmentGranularity: 'COLOR',
      detailSplitDimensions: ['MATERIAL_SKU'],
    }
  }
  return {
    processName: '染色',
    triggerField: 'dyeRequirement',
    assignmentGranularity: 'COLOR',
    detailSplitDimensions: ['MATERIAL_SKU'],
  }
}

function buildBoundMaterialCraftOccurrenceSpec(
  row: BomProcessLinkageBomRow,
  bomItemId: string,
  craftCode: 'CRAFT_131072' | 'CRAFT_3000009',
): BomRouteOccurrenceSpec {
  const isBindingStrip = craftCode === 'CRAFT_131072'
  const craftName = isBindingStrip ? '捆条' : '橡筋定长切割'
  return {
    id: `tech-prod-${toSafeId(bomItemId)}-${craftCode.toLowerCase().replace(/_/g, '-')}`,
    bomItemId,
    routeObjectKey: `BOM:${bomItemId}`,
    processCode: 'SPECIAL_CRAFT',
    processName: isBindingStrip ? '辅助工艺' : '特种工艺',
    entryType: 'CRAFT',
    stageCode: 'PROD',
    stageName: '生产阶段',
    craftCode,
    craftName,
    isSpecialCraft: true,
    selectedTargetObject: isBindingStrip ? '完整面料' : '辅料',
    inputObjectType: isBindingStrip ? 'FABRIC' : 'ACCESSORY',
    outputObjectType: isBindingStrip ? 'BINDING_STRIP' : 'ACCESSORY',
    triggerSource: `物料清单绑定工艺：${describeBomRow(row, bomItemId)} / ${craftName}`,
    assignmentGranularity: 'SKU',
    detailSplitDimensions: ['MATERIAL_SKU', 'GARMENT_SKU'],
    defaultDocType: 'TASK',
    taskTypeMode: 'CRAFT',
    consumesBomItem: true,
  }
}

function describeBomRow(row: BomProcessLinkageBomRow, bomItemId: string): string {
  const name = String(row.materialName || row.materialCode || bomItemId).trim()
  const type = row.type || '物料'
  return `${type}：${name}`
}

function buildPrepOccurrenceSpec(
  row: BomProcessLinkageBomRow,
  bomItemId: string,
  processCode: BomDrivenPrepProcessCode,
): BomRouteOccurrenceSpec {
  const meta = getBomDrivenProcessMeta(processCode)
  const objectType = toBomObjectType(row.type)
  return {
    id: `tech-prep-${toSafeId(bomItemId)}-${processCode.toLowerCase().replace(/_/g, '-')}`,
    bomItemId,
    routeObjectKey: `BOM:${bomItemId}`,
    processCode,
    processName: meta.processName,
    entryType: 'PROCESS_BASELINE',
    stageCode: 'PREP',
    stageName: '准备阶段',
    craftCode: '',
    craftName: meta.processName,
    isSpecialCraft: false,
    inputObjectType: objectType,
    outputObjectType: objectType,
    triggerField: meta.triggerField,
    triggerSource: `物料清单自动生成：${describeBomRow(row, bomItemId)} / ${bomTriggerFieldLabel[meta.triggerField]}`,
    assignmentGranularity: meta.assignmentGranularity,
    detailSplitDimensions: meta.detailSplitDimensions,
    defaultDocType: 'PREPARATION_ORDER',
    taskTypeMode: 'PROCESS',
  }
}

