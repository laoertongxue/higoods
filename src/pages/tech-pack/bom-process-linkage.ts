function listRequiredOccurrenceSpecs(bomRows: BomProcessLinkageBomRow[]): BomRouteOccurrenceSpec[] {
  return bomRows.flatMap((row, index) => {
    const bomItemId = String(row.id || `BOM-${index + 1}`).trim()
    const prepSpecs = getRequiredPrepProcessCodesForRow(row)
      .map((processCode) => buildPrepOccurrenceSpec(row, bomItemId, processCode))
    const productionSpecs: BomRouteOccurrenceSpec[] = []
    if (row.type === '面料') productionSpecs.push(buildCutOccurrenceSpec(row, bomItemId))
    const usageCodes = new Set(row.usageProcessCodes ?? [])
    if (row.type === '面料' && [...BINDING_STRIP_CODES].some((code) => usageCodes.has(code))) {
      productionSpecs.push(buildBoundMaterialCraftOccurrenceSpec(row, bomItemId, 'CRAFT_131072'))
    }
    if (row.type === '辅料' && [...ELASTIC_FIXED_LENGTH_CODES].some((code) => usageCodes.has(code))) {
      productionSpecs.push(buildBoundMaterialCraftOccurrenceSpec(row, bomItemId, 'CRAFT_3000009'))
    }
    if (row.type === '成衣') {
      if ([...GARMENT_HEAT_TRANSFER_CODES].some((code) => usageCodes.has(code))) {
        productionSpecs.push(buildGarmentCraftOccurrenceSpec(row, bomItemId, 'AUX_HEAT_TRANSFER', '烫画'))
      }
      if ([...GARMENT_DIRECT_PRINT_CODES].some((code) => usageCodes.has(code))) {
        productionSpecs.push(buildGarmentCraftOccurrenceSpec(row, bomItemId, 'AUX_DIRECT_PRINT', '直喷'))
      }
    }
    return [...prepSpecs, ...productionSpecs]
  })
}

function buildAutoGeneratedOccurrence(spec: BomRouteOccurrenceSpec): BomDrivenPrepTechnique {
  return {
    id: spec.id,
    entryType: spec.entryType,
    stageCode: spec.stageCode,
    stage: spec.stageName,
    processCode: spec.processCode,
    process: spec.processName,
    craftCode: spec.craftCode,
    technique: spec.craftName,
    assignmentGranularity: spec.assignmentGranularity,
    ruleSource: 'INHERIT_PROCESS',
    detailSplitMode: 'COMPOSITE',
    detailSplitDimensions: [...spec.detailSplitDimensions],
    defaultDocType: spec.defaultDocType,
    taskTypeMode: spec.taskTypeMode,
    isSpecialCraft: spec.isSpecialCraft,
    selectedTargetObject: spec.selectedTargetObject,
    targetObject: spec.selectedTargetObject === '成衣'
      ? 'GARMENT_SEMI'
      : spec.selectedTargetObject === '完整面料'
        ? 'FABRIC'
        : spec.selectedTargetObject === '辅料'
          ? 'ACCESSORY'
          : spec.inputObjectType === 'FABRIC' ? 'FABRIC' : 'BOM_MATERIAL',
    targetObjectName: spec.selectedTargetObject === '成衣'
      ? '成衣'
      : spec.selectedTargetObject === '完整面料'
        ? '面料'
        : spec.selectedTargetObject === '辅料'
          ? '辅料'
          : spec.inputObjectType === 'FABRIC' ? '面料' : 'BOM物料',
    supportedTargetObjects: spec.selectedTargetObject === '成衣'
      ? ['SEMI_FINISHED_GARMENT']
      : spec.selectedTargetObject === '完整面料'
        ? ['FULL_FABRIC']
        : spec.selectedTargetObject === '辅料'
          ? ['ACCESSORY']
          : undefined,
    supportedTargetObjectLabels: spec.selectedTargetObject === '成衣'
      ? ['成衣']
      : spec.selectedTargetObject === '完整面料'
        ? ['完整面料']
        : spec.selectedTargetObject === '辅料'
          ? ['辅料']
          : undefined,
    triggerSource: spec.triggerSource,
    difficulty: '中等',
    remark: '',
    source: '字典引用',
    sourceType: 'BOM',
    triggerField: spec.triggerField,
    linkedBomItemIds: [spec.bomItemId],
    routeObjectKey: spec.routeObjectKey,
    inputObjectType: spec.inputObjectType,
    outputObjectType: spec.outputObjectType,
    consumedBomItemIds: spec.consumesBomItem ? [spec.bomItemId] : [],
    predecessorEntryIds: [],
    isAutoGenerated: true,
    canRemoveAutomatically: true,
    hasManualOverride: false,
    manualNotes: '',
    manualFieldsTouched: false,
    requiresRemovalConfirmation: false,
    linkageStatus: '已生成',
  }
}

export function buildAutoGeneratedProcessForCode(processCode: BomDrivenPrepProcessCode): BomDrivenPrepTechnique {
  return buildAutoGeneratedOccurrence(buildPrepOccurrenceSpec({
    id: `legacy-${processCode.toLowerCase()}`,
    type: '其他',
    materialName: '待关联 BOM 物料',
  }, `legacy-${processCode.toLowerCase()}`, processCode))
}

export function isBomDrivenPrepProcessCode(processCode: string): processCode is BomDrivenPrepProcessCode {
  return processCode === 'PRINT'
    || processCode === 'WATER_SOLUBLE'
    || processCode === 'DYE'
    || processCode === 'EMBROIDERY'
}

export function getCanonicalBomDrivenPrepProcessCode(processCode: string): BomDrivenPrepProcessCode | null {
  if (isBomDrivenPrepProcessCode(processCode)) return processCode
  return null
}

export function isBomDrivenPrepTechnique(
  item: Pick<BomDrivenPrepTechniqueCandidate, 'stageCode' | 'processCode'> & Partial<BomDrivenPrepTechniqueCandidate>,
): boolean {
  if (item.stageCode !== 'PREP') return false
  if (!getCanonicalBomDrivenPrepProcessCode(item.processCode)) return false
  if (item.sourceType === 'MANUAL') return false
  return item.sourceType === 'BOM' || item.isAutoGenerated === true || item.sourceType === undefined
}

export function hasManualPrepProcessContent(item: Partial<BomDrivenPrepTechniqueCandidate>): boolean {
  if (
    item.hasManualOverride
      || item.manualFieldsTouched
      || String(item.manualNotes || '').trim()
  ) {
    return true
  }
  if (item.sourceType === 'BOM' || item.isAutoGenerated === true) return false
  return Boolean(String(item.remark || '').trim())
}

function isBomDrivenOccurrence(item: BomDrivenPrepTechniqueCandidate): boolean {
  return item.sourceType === 'BOM'
    || (item.sourceType === undefined && (
      item.isAutoGenerated === true || isBomDrivenPrepTechnique(item)
    ))
}

function getLegacyOccurrenceMatchKey(item: BomDrivenPrepTechniqueCandidate): string {
  const linkedBomItemIds = [...(item.linkedBomItemIds ?? [])]
  if (linkedBomItemIds.length !== 1) return ''
  if (item.processCode === 'SPECIAL_CRAFT') {
    const craftCode = String((item as BomDrivenPrepTechniqueCandidate & { craftCode?: string }).craftCode || '')
    return `BOM:${linkedBomItemIds[0]}:${craftCode}`
  }
  return `BOM:${linkedBomItemIds[0]}:${item.processCode}`
}

function getOccurrenceMatchKey(spec: BomRouteOccurrenceSpec): string {
  return `BOM:${spec.bomItemId}:${spec.entryType === 'CRAFT' ? spec.craftCode : spec.processCode}`
}

// 仅同步技术包内的工艺路线；本函数不创建工程任务，也不写入生产准备时效。
export function syncTechPackProcessesFromBom<T extends BomDrivenPrepTechniqueCandidate>(
  techniques: T[],
  bomRows: BomProcessLinkageBomRow[],
): SyncPreparationProcessesFromBomResult<T> {
  const requiredSpecs = listRequiredOccurrenceSpecs(bomRows)
  const requiredByKey = new Map(requiredSpecs.map((spec) => [getOccurrenceMatchKey(spec), spec]))
  const existingByKey = new Map<string, T>()
  const keptItems: T[] = []
  const removedProcessCodes: BomDrivenPrepProcessCode[] = []
  const pendingConfirmationProcessCodes: BomDrivenPrepProcessCode[] = []
  const removedOccurrenceIds: string[] = []
  const pendingConfirmationOccurrenceIds: string[] = []
  const migratedIds = new Map<string, string>()

  techniques.forEach((item) => {
    const normalizedItem = {
      ...item,
      detailSplitDimensions: [...item.detailSplitDimensions],
      linkedBomItemIds: [...(item.linkedBomItemIds ?? [])],
      consumedBomItemIds: [...(item.consumedBomItemIds ?? [])],
      predecessorEntryIds: item.predecessorEntryIds ? [...item.predecessorEntryIds] : undefined,
    } as unknown as T
    // 旧版按 BOM 记录的裁剪节点就是当前自动裁剪节点，保留其内容并迁移引用。
    const legacyBomCut = normalizedItem.processCode === 'CUT_PANEL'
      && normalizedItem.sourceType === undefined
      && (normalizedItem.linkedBomItemIds ?? []).length === 1
    if (!isBomDrivenOccurrence(normalizedItem) && !legacyBomCut) {
      keptItems.push(normalizedItem)
      return
    }

    const matchKey = getLegacyOccurrenceMatchKey(normalizedItem)
    const spec = requiredByKey.get(matchKey)
    if (spec && !existingByKey.has(matchKey)) {
      existingByKey.set(matchKey, normalizedItem)
      migratedIds.set(normalizedItem.id, spec.id)
      return
    }
    if (hasManualPrepProcessContent(normalizedItem)) {
      keptItems.push({
        ...normalizedItem,
        requiresRemovalConfirmation: true,
        linkageStatus: '待确认',
      })
      pendingConfirmationOccurrenceIds.push(normalizedItem.id)
      const prepCode = getCanonicalBomDrivenPrepProcessCode(normalizedItem.processCode)
      if (prepCode) pendingConfirmationProcessCodes.push(prepCode)
      return
    }
    removedOccurrenceIds.push(normalizedItem.id)
    const prepCode = getCanonicalBomDrivenPrepProcessCode(normalizedItem.processCode)
    if (prepCode) removedProcessCodes.push(prepCode)
  })

  const generatedOccurrenceIds: string[] = []
  const generatedProcessCodes: BomDrivenPrepProcessCode[] = []
  const generatedItems = requiredSpecs.map((spec) => {
    const matchKey = getOccurrenceMatchKey(spec)
    const existing = existingByKey.get(matchKey)
    const generated = buildAutoGeneratedOccurrence(spec)
    generatedOccurrenceIds.push(spec.id)
    const prepCode = getCanonicalBomDrivenPrepProcessCode(spec.processCode)
    if (prepCode) generatedProcessCodes.push(prepCode)
    return {
      ...generated,
      ...(existing ?? {}),
      id: spec.id,
      entryType: spec.entryType,
      stageCode: spec.stageCode,
      stage: spec.stageName,
      processCode: spec.processCode,
      process: spec.processName,
      craftCode: spec.craftCode,
      technique: spec.craftName,
      isSpecialCraft: spec.isSpecialCraft,
      selectedTargetObject: spec.selectedTargetObject,
      linkedBomItemIds: [spec.bomItemId],
      routeObjectKey: spec.routeObjectKey,
      inputObjectType: spec.inputObjectType,
      outputObjectType: spec.outputObjectType,
      consumedBomItemIds: spec.consumesBomItem ? [spec.bomItemId] : [],
      sourceType: 'BOM',
      triggerField: spec.triggerField,
      triggerSource: spec.triggerSource,
      isAutoGenerated: true,
      canRemoveAutomatically: true,
      requiresRemovalConfirmation: false,
      linkageStatus: '已生成',
      predecessorEntryIds: existing?.predecessorEntryIds ? [...existing.predecessorEntryIds] : [],
    } as unknown as T
  })

  const uniquePrepCodes = (codes: BomDrivenPrepProcessCode[]) => [...new Set(codes)]
  return {
    techniques: [...keptItems, ...generatedItems].map((item) => ({
      ...item,
      predecessorEntryIds: item.predecessorEntryIds?.map((id) => migratedIds.get(id) ?? id),
    })),
    generatedProcessCodes: uniquePrepCodes(generatedProcessCodes),
    removedProcessCodes: uniquePrepCodes(removedProcessCodes),
    pendingConfirmationProcessCodes: uniquePrepCodes(pendingConfirmationProcessCodes),
    generatedOccurrenceIds,
    removedOccurrenceIds,
    pendingConfirmationOccurrenceIds,
  }
}
