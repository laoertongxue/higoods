import { useEmptyInventoryQualityFixture } from './helpers/inventory-quality-empty-fixture.ts'
import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'

test('记录筛选跨页导出全部结果；列隐藏、冻结、拖序及每页量刷新保留，当前页与排序复位',async({page},testInfo)=>{
 test.setTimeout(90000)
 await page.addInitScript(()=>{(window as any).__name=(value:unknown)=>value})
 await page.goto('/fcs/quality-management/records')
 await page.locator('[data-qm-filter="sourceKind"]').selectOption('PRODUCTION_RETURN')
 await page.locator('[data-qm-action="query"]').click()
 const root=page.locator('[data-quality-management-page]');await expect(root.locator('h2').filter({hasText:'质检记录汇总 ·'})).toContainText('12条');const title=await root.innerText(),total=Number(title.match(/质检记录汇总 · (\d+)条/)?.[1])
 expect(total).toBeGreaterThan(10)
 await page.locator('[data-qm-field="pageSize"]').selectOption('10')
 await expect(root.locator('tbody tr')).toHaveCount(10)
 await page.locator('[data-qm-action="next-page"]').click()
 const downloadPromise=page.waitForEvent('download');await page.locator('[data-qm-action="export"]').click()
 const download=await downloadPromise,csv=await readFile((await download.path())!,'utf8'),lines=csv.trim().split('\n')
 expect(lines).toHaveLength(total+1);expect(lines[0]).not.toContain('操作');expect(lines.slice(1).every(row=>row.includes('生产回货后道QC'))).toBe(true)
 await testInfo.attach('filtered-all-pages-export.csv',{body:csv,contentType:'text/csv'})
 await page.locator('[data-qm-action="open-column-settings"]').click()
 await expect(page.locator('[data-qm-action="toggle-column-visibility"][data-qm-column-key="displayNo"]')).toBeDisabled()
 await page.locator('[data-qm-action="toggle-column-visibility"][data-qm-column-key="quantity"]').uncheck()
 await page.locator('[data-qm-action="toggle-column-freeze"][data-qm-column-key="displayNo"]').check()
 await page.locator('[data-standard-list-column-drag][data-drag-source="status"]').dragTo(page.locator('[data-standard-list-column-drag][data-drop-target="party"]'))
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('higood:quality-list:records')!))
 expect(saved.pageSize).toBe(10);expect(saved.visibleKeys).not.toContain('quantity');expect(saved.frozenKeys).toContain('displayNo');expect(saved.order.indexOf('status')).toBeLessThan(saved.order.indexOf('party'))
 await page.locator('[data-qm-action="close-column-settings"]').last().click()
 await expect(root.locator('th[data-column-key="quantity"]')).toHaveCount(0)
 await expect(root.locator('th[data-column-key="displayNo"]')).toHaveClass(/sticky/)
 await page.locator('[data-qm-action="sort-column"][data-column-key="status"]').click()
 await page.reload();await expect(page.locator('[data-qm-field="pageSize"]')).toHaveValue('10')
 const after=await page.evaluate(()=>JSON.parse(localStorage.getItem('higood:quality-list:records')!));expect(after).toEqual(saved)
 await expect(root.locator('th[data-column-key="quantity"]')).toHaveCount(0)
 await expect(root.locator('th[data-column-key="displayNo"]')).toHaveClass(/sticky/)
 const heads=await root.locator('th[data-column-key]').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('data-column-key')))
 expect(heads.indexOf('status')).toBeLessThan(heads.indexOf('party'))
 await expect(page.locator('[data-qm-action="prev-page"]')).toBeDisabled()
 await testInfo.attach('record-list-preferences',{body:JSON.stringify({total,saved,after,heads}),contentType:'application/json'})
 await testInfo.attach('record-list-refreshed',{body:await page.screenshot({fullPage:true}),contentType:'image/png'})
})

test.beforeEach(async ({page,baseURL})=>{await useEmptyInventoryQualityFixture(page,baseURL)})
