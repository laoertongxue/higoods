  await page.addInitScript(() => localStorage.setItem('higood-pcs-design-revision-list-preferences-v2', JSON.stringify({ order: ['code', 'style', 'select'], visibleKeys: ['code', 'style', 'select'], frozenKeys: ['code'], pageSize: 10 })))
  await page.goto('/pcs/production-preparation/design-revision')
  const table = page.locator('[data-independent-sampling-table]')
  await expect(table.locator('thead th').first()).toHaveText('勾选')
  await table.locator('tbody tr').first().locator('td').first().locator('input').check()
