const report = '/fcs/sewing-outsourcing/daily-return-report'
const summary = '/fcs/sewing-outsourcing/daily-return-summary'
async function actorWithCapacity(page: Page): Promise<{ actorId: string; assignmentId: string; capacity: number }> {
  return page.evaluate(async () => {
    const records = await import('/src/data/fcs/ppic-daily-return-records.ts')
    for (const actor of records.PPIC_DAILY_DEMO_MEMBERS.filter(p => !p.leader)) {
      const login = await import('/src/data/fcs/factory-onboarding-ppic.ts')
      Object.assign(login.SEWING_OUTSOURCING_DEMO_CURRENT_PPIC, login.getOnboardingPpicOptionById(actor.id)!)
      const task = records.getPpicDailyReturnView().tasks.find(t => !t.capacity.conflict && t.capacity.available > 10)
      if (task) return { actorId: actor.id, assignmentId: task.task.assignmentId, capacity: task.capacity.available }
    }
    throw new Error('正常场景需要有已确认应回来源的第三方车缝任务')
  })
}

