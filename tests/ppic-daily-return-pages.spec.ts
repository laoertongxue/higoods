const report = '/fcs/sewing-outsourcing/daily-return-report'
type WorklistTask = { ownerId: string; ownerName: string; assignmentId: string; taskNo: string; productionOrderNo: string; capacity: number; basisVersion: string }
async function worklistTask(page: Page): Promise<WorklistTask> {
  return page.evaluate(async () => {
    const records = await import('/src/data/fcs/ppic-daily-return-records.ts')
    const task = records.getPpicDailyWorklistView().rows.find((row: any) => row.ownerActive && !row.capacity.conflict && row.capacity.available > 10)
    if (!task) throw new Error('正常场景需要有已确认应回来源、可新增承诺的第三方车缝任务')
    return { ownerId: task.task.ownerId, ownerName: task.ownerName, assignmentId: task.task.assignmentId, taskNo: task.basis.taskNo, productionOrderNo: task.basis.productionOrderNo, capacity: task.capacity.available, basisVersion: task.basis.basisVersion }
  })
}
function rowFor(page: Page, task: WorklistTask) {
  return page.locator('[data-standard-list-table-section] tbody tr', { hasText: task.taskNo })
}

