import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { chromium } from 'playwright'

const base = process.env.DYE_BARCODE_BASE_URL || 'http://127.0.0.1:5188'
const output = 'output/playwright/dye-barcode-weight'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1366, height: 768 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const results = []
try {
  await page.goto(`${base}/fcs/craft/dyeing/work-orders`)
  await page.locator('[data-dye-work-orders-root]').waitFor()
  await page.locator('[data-dye-work-orders-field="pageSize"]').selectOption('50')
  async function open(unit) {
    const id = unit === 'Yard' ? 'DYE-DISPATCH-DEMO-1' : 'DWO-001'
    const button = page.locator(`[data-dye-work-orders-action="barcodes"][data-id="${id}"]`)
    await button.click()
    return id
  }
  const field = name => page.locator(`[data-dye-barcode-inner] [data-dye-barcode-field="${name}"]`)
  const action = name => page.locator(`[data-dye-barcode-root] [data-dye-barcode-action="${name}"]`)
  const theory = () => page.locator('[data-dye-barcode-theory]').innerText()
  await open('米')
  await action('add').click()
  for (const [name, value] of Object.entries({ qty: '100', weightKg: '12.345', widthCm: '160', gsm: '220', vatNo: 'QA-WEIGHT-001' })) await field(name).fill(value)
  await field('qty').fill('120')
  assert.equal(await field('weightKg').inputValue(), '12.345', '修改卷长不得覆盖实称重量')
  await field('widthCm').fill('150')
  await field('gsm').fill('200')
  assert.equal(await field('weightKg').inputValue(), '12.345', '修改幅宽或克重不得覆盖实称重量')
  await field('weightKg').fill('18.789')
  assert.equal(await field('qty').inputValue(), '120', '修改实称重量不得反算卷长')
  assert.equal(await field('meters').inputValue(), '120.00', '修改实称重量不得覆盖米数')
  await field('meters').fill('50')
  assert.equal(await field('qty').inputValue(), '50.00')
  assert.equal(await field('weightKg').inputValue(), '18.789')
  assert.equal(await theory(), '15.000 kg')
  await field('qty').fill('100')
  assert.equal(await field('weightKg').inputValue(), '18.789')
  await action('save').click()
  await page.locator('[data-dye-barcode-inner]').waitFor({ state: 'detached' })
  const rollId = await page.locator('[data-dye-barcode-body] tbody tr').filter({ hasText: '18.789' }).locator('[data-dye-barcode-action="edit"]').getAttribute('data-id')
  await page.locator(`[data-dye-barcode-action="edit"][data-id="${rollId}"]`).click()
  assert.equal(await field('weightKg').inputValue(), '18.789', '保存重开保持实称重量')
  await page.screenshot({ path: `${output}/edit-meter.png` })
  await action('close-inner').first().click()
  await page.locator('[data-dye-barcode-inner]').waitFor({ state: 'detached' })
  await page.locator(`[data-dye-barcode-select="${rollId}"]`).check()
  await action('batch').click()
  await field('gsm').fill('220')
  assert.equal(await theory(), '33.000 kg')
  assert.equal(await field('weightKg').inputValue(), '', '批量修改克重不得自动填入重量')
  await action('save').click()
  await page.locator('[data-dye-barcode-inner]').waitFor({ state: 'detached' })
  await page.locator(`[data-dye-barcode-action="edit"][data-id="${rollId}"]`).click()
  assert.equal(await field('weightKg').inputValue(), '18.789', '批量修改留空保持各卷实称重量')
  assert.equal(await field('qty').inputValue(), '100')
  await action('close-inner').first().click()
  await page.locator('[data-dye-barcode-inner]').waitFor({ state: 'detached' })
  await page.locator(`[data-dye-barcode-action="print-one"][data-id="${rollId}"]`).click()
  const print = page.frameLocator('[data-dye-barcode-print]').locator('body')
  await print.locator('svg').waitFor()
  const label = await print.innerText()
  assert(label.includes('实称重量：18.789 kg'))
  assert(label.includes('理论重量（仅参考）：33.000 kg'))
  await page.screenshot({ path: `${output}/label-preview.png` })
  results.push('米制编辑、实称独立、理论只读、保存重开、批量留空、标签区分和三位小数')
  await action('close-inner').first().click()
  await page.locator('[data-dye-barcode-inner]').waitFor({ state: 'detached' })
  await action('close').click()
  await open('Yard')
  await action('add').click()
  for (const [name, value] of Object.entries({ qty: '100', weightKg: '24.321', widthCm: '160', gsm: '200' })) await field(name).fill(value)
  await field('meters').fill('45.72')
  assert.equal(await field('qty').inputValue(), '50.00')
  assert.equal(await field('weightKg').inputValue(), '24.321')
  assert.equal(await theory(), '14.630 kg')
  await page.setViewportSize({ width: 1280, height: 720 })
  const bounds = await page.locator('[data-dye-barcode-inner] section').boundingBox()
  assert(bounds && bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 1280 && bounds.y + bounds.height <= 720)
  await page.screenshot({ path: `${output}/edit-yard-1280.png` })
  results.push('Yard/米独立换算、实称保留、理论按米换算、1280×720弹窗可见')
  assert.equal(errors.length, 0, errors.join('\n'))
  await writeFile(`${output}/results.json`, JSON.stringify({ results, errors }, null, 2))
  console.log(`PASS ${results.join('；')}`)
} finally {
  await context.close()
  await browser.close()
}
